//! The files a run writes: per mod `<key>.gif`, `<key>.png`, `<key>.json`,
//! plus `index.md` with the hotlink URLs. `state.json` is written by the CLI.

pub mod gif;
pub mod png;
pub mod shields;

use std::path::Path;

use anyhow::{Context, Result};

use crate::render::card::{self, CardData};
use crate::render::Theme;

/// What was written for one mod.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Written {
    pub gif_bytes: usize,
    pub png_bytes: usize,
}

/// Renders one card and writes its three files into `dir`.
pub fn write_mod(dir: &Path, key: &str, data: &CardData, theme: &Theme) -> Result<Written> {
    let frames = card::render(data, theme);
    let gif = gif::encode(&frames, theme.background, card::DELAY_CS)?;
    let png = match frames.first() {
        Some(f) => png::encode(f)?,
        None => Vec::new(),
    };
    let json = shields::to_json(&shields::endpoint(
        &data.label,
        data.status,
        data.version.as_deref(),
        &data.build,
        theme,
    ));
    let put = |name: String, bytes: &[u8]| -> Result<()> {
        let p = dir.join(name);
        std::fs::write(&p, bytes).with_context(|| format!("cannot write {}", p.display()))
    };
    put(format!("{key}.gif"), &gif)?;
    put(format!("{key}.png"), &png)?;
    put(format!("{key}.json"), json.as_bytes())?;
    Ok(Written {
        gif_bytes: gif.len(),
        png_bytes: png.len(),
    })
}

/// Where a published file is served from.
pub fn raw_url(repo: &str, branch: &str, file: &str) -> String {
    format!("https://raw.githubusercontent.com/{repo}/{branch}/{file}")
}

/// Percent-encodes a URL for use as a query value.
pub fn query_escape(s: &str) -> String {
    s.bytes()
        .map(|b| match b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => (b as char).to_string(),
            _ => format!("%{b:02X}"),
        })
        .collect()
}

/// The paste-ready snippets for one mod.
pub fn snippets(repo: &str, branch: &str, key: &str, label: &str) -> String {
    let gif = raw_url(repo, branch, &format!("{key}.gif"));
    let png = raw_url(repo, branch, &format!("{key}.png"));
    let json = raw_url(repo, branch, &format!("{key}.json"));
    let shield = format!("https://img.shields.io/endpoint?url={}", query_escape(&json));
    format!(
        "## {label} (`{key}`)\n\n\
         Nexus Mods description (BBCode):\n\n```\n[img]{gif}[/img]\n```\n\n\
         Markdown card:\n\n```\n![{label} status]({gif})\n```\n\n\
         Markdown badge (shields.io):\n\n```\n![{label}]({shield})\n```\n\n\
         Still image: {png}\n"
    )
}

/// `index.md` for the badges branch.
pub fn index_md(repo: &str, branch: &str, mods: &[(&str, &str)]) -> String {
    let mut out = String::from(
        "# baise badges\n\nGenerated by [baise](https://github.com/KiefBC/baise). \
         This branch is rewritten by the workflow on every run; do not commit to it.\n\n",
    );
    for (key, label) in mods {
        out.push_str(&snippets(repo, branch, key, label));
        out.push('\n');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn urls() {
        assert_eq!(
            raw_url("KiefBC/desert-modding", "badges", "desert-tooling.gif"),
            "https://raw.githubusercontent.com/KiefBC/desert-modding/badges/desert-tooling.gif"
        );
        assert_eq!(query_escape("https://a.b/c d"), "https%3A%2F%2Fa.b%2Fc%20d");
        let s = snippets("o/r", "badges", "k", "K");
        assert!(s.contains("[img]https://raw.githubusercontent.com/o/r/badges/k.gif[/img]"));
        assert!(s.contains("endpoint?url=https%3A%2F%2Fraw.githubusercontent.com%2Fo%2Fr%2Fbadges%2Fk.json"));
    }
}
